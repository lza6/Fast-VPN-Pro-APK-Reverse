#!/usr/bin/env python3
"""nodes.json -> mihomo config: 每节点一个 socks listener (127.0.0.1:24000+i)"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
BASE_PORT = 24000


def build(nodes_path=None, out=None, base_port=BASE_PORT, dialer=None):
    """dialer: 可选, 形如 127.0.0.1:10808 —— 经本机已有隧道拨号到 SS 节点
    (本机直连 DigitalOcean 网段被墙时使用, 仅影响测试路径, 不影响节点本身)"""
    nodes_path = nodes_path or os.path.join(HERE, 'nodes.json')
    out = out or os.path.join(HERE, 'mihomo_config.yaml')
    d = json.load(open(nodes_path, encoding='utf-8'))
    nodes = d['node_list']
    lines = ['# generated by build_mihomo.py',
             'log-level: warning',
             'allow-lan: false',
             'mode: direct',
             'ipv6: false',
             'proxies:']
    dial_suffix = ''
    if dialer:
        lines.append(f'  - {{name: "__dialer", type: http, server: {dialer.split(":")[0]}, '
                     f'port: {dialer.split(":")[1]}}}')
        dial_suffix = ', dialer-proxy: "__dialer"'
    portmap = []
    for i, n in enumerate(nodes):
        name = f"n{i:03d}_{n.get('iso_code','??')}_{n['server']}"
        lines.append(f"  - {{name: \"{name}\", type: ss, server: {n['server']}, "
                     f"port: {n['server_port']}, cipher: {n['method']}, "
                     f"password: \"{n['password']}\", udp: true{dial_suffix}}}")
        portmap.append({'idx': i, 'name': name, 'socks_port': base_port + i,
                        'server': n['server'], 'server_port': n['server_port'],
                        'iso': n.get('iso_code'), 'city': n.get('city'), 'isp': n.get('isp')})
    lines.append('listeners:')
    for pm in portmap:
        lines.append(f"  - {{name: \"{pm['name']}\", type: socks, listen: 127.0.0.1, "
                     f"port: {pm['socks_port']}, proxy: \"{pm['name']}\", udp: false}}")
    lines.append('rules:')
    lines.append('  - MATCH,DIRECT')
    open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    json.dump({'base_port': base_port, 'portmap': portmap},
              open(os.path.join(HERE, 'portmap.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    print(f'{len(nodes)} nodes -> {out} (socks {base_port}..{base_port+len(nodes)-1})')


if __name__ == '__main__':
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument('nodes', nargs='?', default=None)
    ap.add_argument('out', nargs='?', default=None)
    ap.add_argument('--base-port', type=int, default=BASE_PORT)
    ap.add_argument('--dialer', default=None, help='如 127.0.0.1:10808, 经本机隧道拨号')
    a = ap.parse_args()
    build(a.nodes, a.out, a.base_port, a.dialer)
